// Package confwatch 提供并发安全的配置热更新能力。
//
// 核心模型是一条单向的发布流水线：读取配置源 -> 解码 -> 拷贝 -> 应用默认值 ->
// 校验 -> 构建快照 -> 原子发布。发布之前的任何一步失败，当前有效配置都保持不变。
//
// # 必须区分的四件事
//
// 1. 原子发布（atomic publication）
//
// Manager 内部用 atomic.Pointer 保存指向快照的指针。atomic.Pointer 的 Store 具有
// release 语义、Load 具有 acquire 语义：所有在 Store 之前完成的写入，对之后观察
// 到该指针的 Load 都可见。因此读者要么看到旧快照，要么看到新快照，不会看到混合
// 状态，也不需要加锁。版本号、摘要、时间戳与配置值放在同一个快照对象里，所以它们
// 之间天然一致，不会出现"读到新版本号配旧配置"这类撕裂。
//
// 2. 对象不可变（immutability）
//
// 每次更新都从零开始解码出一个全新的 T，绝不复用上一份快照的内部缓冲区，也绝不
// 把已发布的对象再传给任何可能写入的地方。快照一旦发布，库内部不再写它，因此
// "旧快照在后续更新后内容不变"是库的承诺，而不是靠拷贝维护的。
//
// 3. 快照读取（snapshot reading）
//
// Snapshot 是值类型，Get 返回它的拷贝，只包含 header 与 T 本身的拷贝。读取路径
// 只有一次 atomic.Pointer.Load 和一次结构体拷贝，无锁、不阻塞、不分配。
//
// 4. 调用方持有的配置引用（caller-held references）
//
// 如果 T 含有 map、slice、指针或接口等引用类型字段，Value 返回的 T 与快照共享
// 这些字段的底层数据。Go 的类型系统无法表达"深不可变"，因此这里存在一条 API
// 层面无法封死的边界：
//
//	cfg := m.Get().Value()
//	cfg.Addr = "127.0.0.1:1" // 安全：修改的是本地拷贝里的值类型字段
//	cfg.Tags["k"] = "v"      // 危险：修改的是已发布快照内部的 map
//
// 由此产生的调用方约束：
//
//   - T 的引用类型字段在 Value 返回后视为只读，不要写入。
//   - 不要把这些字段取出后长期缓存并写入；需要写入请使用自己的深拷贝。
//   - 需要彻底隔离时使用 WithCopyFunc 在发布前做一次深拷贝：它保证被发布的对象
//     不与解码器、默认值函数或任何外部缓存共享内存。
//   - 排查方式：在 -race 下同时跑高频读取与高频 Reload，断言配置内部的不变量
//     （见 TestConcurrentSnapshotIntegrity）。
//
// # 并发约定
//
//   - Get 可在任意 goroutine 并发调用。
//   - Reload/TryReload/Close 之间通过写者令牌串行化：同一时刻最多只有一个发布在
//     进行，因此版本号单调递增、不重复、不会相互覆盖。
//   - 更新失败不会改变当前快照，只记录 LastError 并返回错误。
//   - Manager 必须通过 Open 构造。零值 Manager 不可用：写入方法返回
//     ErrNotInitialized，Get 返回无效快照。Manager 不可被拷贝。
